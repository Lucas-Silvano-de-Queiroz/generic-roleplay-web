import { expect, test } from "@playwright/test";
import { confirmDelete, loginInBrowser, newEmail, registerInBrowser } from "./fixtures/api";

test("cadastro, CRUD completo, conflito de schema, cascata e logout em 360 px", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 });
  page.on("dialog", (dialog) => dialog.accept());
  const email = newEmail();
  await registerInBrowser(page, email);
  await loginInBrowser(page, email);
  await page.getByRole("link", { name: "Criar sistema", exact: true }).first().click();
  await page.getByLabel("Nome", { exact: true }).fill("Biblioteca de teste");
  await page.getByLabel("Descrição (opcional)").fill("Texto\n✨");
  await page.getByRole("button", { name: "Criar sistema", exact: true }).click();
  await expect(page).toHaveURL(/\/systems\/[\da-f-]+$/);
  const systemURL = page.url();
  await page.getByRole("link", { name: "Criar coleção", exact: true }).first().click();
  await page.getByLabel("Nome", { exact: true }).fill("Personagens");
  await page.getByLabel("Identificador", { exact: true }).fill("c".repeat(64));
  await page.getByRole("button", { name: "Criar coleção", exact: true }).click();
  await expect(page).toHaveURL(/\/collections\/[\da-f-]+$/);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const collectionURL = page.url();
  await page.getByRole("link", { name: "Criar template", exact: true }).first().click();
  await page.getByLabel("Nome", { exact: true }).fill("Ficha de personagem");
  await page.getByLabel("Identificador", { exact: true }).fill("character");
  await page.getByRole("button", { name: "Adicionar campo" }).click();
  let group = page.getByRole("group").nth(0);
  await group.getByLabel("Chave técnica").fill("name");
  await group.getByLabel("Rótulo", { exact: true }).fill("Nome do personagem");
  await group.getByLabel("Obrigatório", { exact: true }).check();
  await page.getByRole("button", { name: "Adicionar campo" }).click();
  group = page.getByRole("group").nth(1);
  await group.getByLabel("Chave técnica").fill("notes");
  await group.getByLabel("Rótulo", { exact: true }).fill("Notas");
  await group.getByLabel("Apresentação").selectOption("textarea");
  await page.getByRole("button", { name: "Criar template", exact: true }).click();
  await expect(page).toHaveURL(/\/templates\/[\da-f-]+$/);
  const templateURL = page.url();
  await page.getByRole("link", { name: "Criar registro", exact: true }).click();
  await page.getByLabel("Nome do personagem (obrigatório)").fill("  Amizade  ");
  await page.getByRole("checkbox").check();
  const literal = "Material: visco\n\n✨ <script>window.grpExecuted=true</script>";
  await page.getByLabel("Notas", { exact: true }).fill(literal);
  await page.getByRole("button", { name: "Salvar registro" }).click();
  await expect(page).toHaveURL(/\/records\/[\da-f-]+$/);
  const recordURL = page.url();
  await expect(page.getByText(literal, { exact: true })).toBeVisible();
  await page.getByRole("link", { name: "Editar", exact: true }).click();
  await page.getByLabel("Nome do personagem (obrigatório)").fill("Novo nome");
  await expect(page.getByLabel("Notas", { exact: true })).toHaveValue(literal);
  await page.getByRole("button", { name: "Salvar registro" }).click();
  await page.reload();
  await expect(page.getByText(literal, { exact: true })).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { grpExecuted?: boolean }).grpExecuted)).toBeUndefined();
  await page.goto(templateURL + "/edit");
  await page.getByRole("group").nth(0).getByLabel("Rótulo", { exact: true }).fill("Nome atualizado");
  await page.getByRole("button", { name: "Salvar alterações" }).click();
  await expect(page).toHaveURL(templateURL);
  await page.goto(templateURL + "/edit");
  await page.getByRole("group").nth(0).getByLabel("Limite de texto").fill("1");
  await page.getByRole("button", { name: "Salvar alterações" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "incompatível" })).toBeVisible();
  await expect(page.getByRole("group").nth(0).getByLabel("Limite de texto")).toHaveValue("1");
  await page.goto(recordURL);
  await confirmDelete(page);
  await expect(page).toHaveURL(templateURL);
  await page.getByRole("link", { name: "Criar registro", exact: true }).click();
  await page.getByLabel("Nome atualizado (obrigatório)").fill("Descendente");
  await page.getByRole("button", { name: "Salvar registro" }).click();
  await expect(page).toHaveURL(/\/records\/[\da-f-]+$/);
  const descendantURL = page.url();
  await page.goto(templateURL);
  await confirmDelete(page);
  await expect(page).toHaveURL(collectionURL);
  await page.goto(descendantURL);
  await expect(page.getByRole("heading", { name: "Recurso não encontrado" })).toBeVisible();
  await page.goto(collectionURL);
  await confirmDelete(page);
  await expect(page).toHaveURL(systemURL);
  await confirmDelete(page);
  await expect(page).toHaveURL(/\/systems$/);
  await page.getByRole("button", { name: "Sair", exact: true }).click();
  await expect(page).toHaveURL(/\/login\?logout=done$/);
  await page.goto(systemURL);
  await expect(page).toHaveURL(/\/login/);
});
